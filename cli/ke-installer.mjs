#!/usr/bin/env node

import { createHash } from "node:crypto";
import { spawn } from "node:child_process";
import {
  access,
  appendFile,
  cp,
  mkdir,
  readFile,
  writeFile,
} from "node:fs/promises";
import { constants } from "node:fs";
import path from "node:path";
import process from "node:process";
import { createInterface } from "node:readline/promises";
import { gunzipSync } from "node:zlib";

const packageName = "__KE_PACKAGE_NAME__";
const packageVersion = "__KE_PACKAGE_VERSION__";
const embeddedPayload = "__KE_PAYLOAD_BASE64__";
const args = process.argv.slice(2);

if (embeddedPayload.startsWith("__KE_")) {
  throw new Error("This is the CLI source template. Run `npm run build` first.");
}

const payloadFiles = JSON.parse(
  gunzipSync(Buffer.from(embeddedPayload, "base64")).toString("utf8"),
).map((file) => ({
  ...file,
  content: Buffer.from(file.content, "base64"),
}));

function usage() {
  console.log(`
Kintone Expert BSS installer

Usage:
  npx kintone-expert-bss install [options]

Options:
  --directory <path>  Install into this project (default: current directory)
  --yes               Accept defaults and skip confirmation
  --chat-language <language>
                      Preferred chat language (default: English)
  --document-languages <languages>
                      Output languages separated by comma (default: English)
  --skip-deps         Do not install Kintone, browser, or Office dependencies
  --force             Overwrite conflicting KE-managed files
  --help              Show this help
  --version           Show the package version
`);
}

function optionValue(name) {
  const index = args.indexOf(name);
  if (index === -1) return undefined;
  const value = args[index + 1];
  if (!value || value.startsWith("--")) throw new Error(`${name} requires a value`);
  return value;
}

async function exists(target) {
  try {
    await access(target, constants.F_OK);
    return true;
  } catch {
    return false;
  }
}

async function digest(target) {
  return createHash("sha256").update(await readFile(target)).digest("hex");
}

function digestContent(content) {
  return createHash("sha256").update(content).digest("hex");
}

function normalizeLanguage(value, fallback = "English") {
  const normalized = value?.trim().replace(/[\r\n]+/gu, " ");
  return normalized || fallback;
}

function parseDocumentLanguages(value) {
  const languages = (value ?? "English")
    .split(",")
    .map((language) => normalizeLanguage(language, ""))
    .filter(Boolean);
  return [...new Set(languages.length ? languages : ["English"])];
}

function tomlString(value) {
  return `"${value
    .replaceAll("\\", "\\\\")
    .replaceAll("\"", "\\\"")
    .replaceAll("\t", "\\t")}"`;
}

async function writePreferences(target, chatLanguage, documentLanguages) {
  const preferencesPath = path.join(target, ".codex", "ke-preferences.toml");
  await mkdir(path.dirname(preferencesPath), { recursive: true });
  const content = [
    "# Local KE preferences. Generated by the installer and ignored by Git.",
    `chat_language = ${tomlString(chatLanguage)}`,
    `document_languages = [${documentLanguages.map(tomlString).join(", ")}]`,
    "",
  ].join("\n");
  await writeFile(preferencesPath, content, "utf8");
}

async function mergeManagedFile(target, sourceContent, label) {
  const begin = `# >>> KE KIT: ${label} >>>`;
  const end = `# <<< KE KIT: ${label} <<<`;
  const managed = `${begin}\n${sourceContent.toString("utf8").trim()}\n${end}`;

  if (!(await exists(target))) {
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, `${managed}\n`, "utf8");
    return;
  }

  const current = await readFile(target, "utf8");
  const start = current.indexOf(begin);
  const finish = current.indexOf(end);
  if (start >= 0 && finish >= start) {
    const updated =
      current.slice(0, start) + managed + current.slice(finish + end.length);
    await writeFile(target, updated.endsWith("\n") ? updated : `${updated}\n`, "utf8");
    return;
  }

  await appendFile(target, `${current.endsWith("\n") ? "" : "\n"}\n${managed}\n`, "utf8");
}

function run(command, commandArgs, cwd) {
  return new Promise((resolve, reject) => {
    const child = spawn(command, commandArgs, { cwd, stdio: "inherit", shell: false });
    child.on("error", reject);
    child.on("exit", (code) => {
      if (code === 0) resolve();
      else reject(new Error(`${command} exited with code ${code}`));
    });
  });
}

if (args.includes("--help") || args.includes("-h")) {
  usage();
  process.exit(0);
}

if (args.includes("--version") || args.includes("-v")) {
  console.log(packageVersion);
  process.exit(0);
}

if (args[0] !== "install") {
  usage();
  process.exitCode = 1;
} else {
  const target = path.resolve(optionValue("--directory") ?? process.cwd());
  const assumeYes = args.includes("--yes");
  const skipDependencies = args.includes("--skip-deps");
  const force = args.includes("--force");
  const chatLanguageOption = optionValue("--chat-language");
  const documentLanguagesOption = optionValue("--document-languages");
  const preferencesPath = path.join(target, ".codex", "ke-preferences.toml");
  const preferencesExist = await exists(preferencesPath);
  const configurePreferences =
    !preferencesExist || Boolean(chatLanguageOption || documentLanguagesOption);
  let chatLanguage = normalizeLanguage(chatLanguageOption);
  let documentLanguages = parseDocumentLanguages(documentLanguagesOption);
  let terminal;

  console.log(`\nKE Kit ${packageVersion}`);
  console.log(`Target: ${target}`);

  if (!assumeYes) {
    terminal = createInterface({ input: process.stdin, output: process.stdout });
    const answer = await terminal.question("Install KE Kit into this project? (Y/n) ");
    if (answer.trim() && !/^y(?:es)?$/iu.test(answer.trim())) {
      terminal.close();
      console.log("Installation cancelled.");
      process.exit(0);
    }

    if (configurePreferences) {
      if (!chatLanguageOption) {
        chatLanguage = normalizeLanguage(
          await terminal.question(
            "Preferred chat language / Ngôn ngữ chat mong muốn? (English) ",
          ),
        );
      }
      if (!documentLanguagesOption) {
        console.log(
          "Tip: for two output versions, enter languages separated by comma, " +
            "for example: English, Vietnamese",
        );
        documentLanguages = parseDocumentLanguages(
          await terminal.question(
            "Preferred output document language(s) / Ngôn ngữ tài liệu? (English) ",
          ),
        );
      }
    }
    terminal.close();
  }

  await mkdir(target, { recursive: true });
  const mergeFiles = new Set([
    "AGENTS.md",
    "gitignore.template",
    path.join(".codex", "config.toml"),
  ]);
  const conflicts = [];

  for (const file of payloadFiles) {
    const relative = file.path.split("/").join(path.sep);
    if (mergeFiles.has(relative)) continue;
    const destination = path.join(target, relative);
    if (
      (await exists(destination)) &&
      digestContent(file.content) !== (await digest(destination))
    ) {
      conflicts.push(file.path);
    }
  }

  if (conflicts.length && !force) {
    console.error("\nInstallation stopped to protect existing files:");
    for (const conflict of conflicts.slice(0, 20)) console.error(`- ${conflict}`);
    if (conflicts.length > 20) {
      console.error(`- ...and ${conflicts.length - 20} more`);
    }
    console.error("\nRe-run with --force only if KE should replace these managed files.");
    process.exit(2);
  }

  for (const file of payloadFiles) {
    const relative = file.path.split("/").join(path.sep);
    if (mergeFiles.has(relative)) continue;
    const destination = path.join(target, relative);
    await mkdir(path.dirname(destination), { recursive: true });
    await writeFile(destination, file.content);
  }

  await mergeManagedFile(
    path.join(target, "AGENTS.md"),
    payloadFiles.find((file) => file.path === "AGENTS.md").content,
    "PROJECT INSTRUCTIONS",
  );
  await mergeManagedFile(
    path.join(target, ".gitignore"),
    payloadFiles.find((file) => file.path === "gitignore.template").content,
    "GITIGNORE",
  );
  await mergeManagedFile(
    path.join(target, ".codex", "config.toml"),
    payloadFiles.find((file) => file.path === ".codex/config.toml").content,
    "CODEX CONFIG",
  );

  if (configurePreferences) {
    await writePreferences(target, chatLanguage, documentLanguages);
  } else {
    console.log("\nKeeping existing .codex/ke-preferences.toml.");
  }

  const envExample = path.join(
    target,
    "platform",
    "ke-kintone-mcp",
    ".env.example",
  );
  const env = path.join(target, "platform", "ke-kintone-mcp", ".env");
  if (!(await exists(env))) await cp(envExample, env, { errorOnExist: true });

  const manifest = {
    package: packageName,
    version: packageVersion,
    installedAt: new Date().toISOString(),
    files: payloadFiles
      .map((file) => file.path)
      .filter((file) => file !== "gitignore.template")
      .concat(".gitignore"),
  };
  await writeFile(
    path.join(target, ".codex", "ke-kit-manifest.json"),
    `${JSON.stringify(manifest, null, 2)}\n`,
    "utf8",
  );

  if (!skipDependencies) {
    console.log("\nInstalling Kintone MCP runtime...");
    if (process.platform === "win32") {
      await run(
        process.env.ComSpec || "cmd.exe",
        ["/d", "/s", "/c", "npm", "ci", "--prefix", "platform/ke-kintone-mcp"],
        target,
      );
    } else {
      await run("npm", ["ci", "--prefix", "platform/ke-kintone-mcp"], target);
    }

    console.log("\nInstalling Playwright and Chrome DevTools MCP runtimes...");
    if (process.platform === "win32") {
      await run(
        process.env.ComSpec || "cmd.exe",
        ["/d", "/s", "/c", "npm", "ci", "--prefix", "platform/ke-browser-mcp"],
        target,
      );
    } else {
      await run("npm", ["ci", "--prefix", "platform/ke-browser-mcp"], target);
    }

    console.log("\nInstalling OfficeCLI document runtime...");
    if (process.platform === "win32") {
      await run(
        process.env.ComSpec || "cmd.exe",
        ["/d", "/s", "/c", "npm", "ci", "--prefix", "platform/ke-office-cli"],
        target,
      );
    } else {
      await run("npm", ["ci", "--prefix", "platform/ke-office-cli"], target);
    }
  }

  console.log("\nKE Kit installed successfully.");
  if (configurePreferences) {
    console.log(`Chat language: ${chatLanguage}`);
    console.log(`Output document language(s): ${documentLanguages.join(", ")}`);
  } else {
    console.log("Language preferences: existing file preserved");
  }
  console.log("Next:");
  console.log("1. Edit platform/ke-kintone-mcp/.env");
  console.log("2. Run: npm --prefix platform/ke-kintone-mcp run check");
  console.log("3. Run: npm --prefix platform/ke-office-cli run check");
  console.log("4. Open this project in Codex and trust it");
  console.log("5. Let Playwright open Chrome and sign in to Kintone once when asked");
  console.log('6. Start a new chat and say "hello"');
}
